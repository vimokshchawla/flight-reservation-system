WHERE f.dep_datetime < '2026-11-25' AND f.flight_number IN ('AI101','AI102') AND s.seat_number = '4C';

-- Bulk demo bookings: deterministic 5-30% fill per flight
INSERT INTO BOOKING (booking_date, status, passenger_id, seat_id)
SELECT CASE WHEN f.dep_datetime < '2026-11-25' THEN '2026-10-30 10:00:00' ELSE '2026-11-18 14:30:00' END,
       CASE WHEN s.seat_id % 19 = 0 THEN 'Cancelled' WHEN s.seat_id % 29 = 0 AND f.dep_datetime > '2026-11-25' THEN 'Pending' ELSE 'Confirmed' END,
       3 + (s.seat_id * 7 + f.flight_id) % 158, s.seat_id
FROM SEAT s JOIN FLIGHT f ON f.flight_id = s.flight_id
WHERE f.flight_id > 3 AND s.seat_number <> '4C'
  AND (s.seat_id * 37 + f.flight_id * 11) % 100 < 5 + (f.flight_id * 29) % 26;

-- Tickets for bookings that were paid (Confirmed, or Cancelled after payment)
INSERT INTO TICKET (ticket_number, issue_date, booking_id)
SELECT CONCAT('TKT-', f.flight_number, '-', LPAD(b.booking_id, 5, '0')), b.booking_date, b.booking_id
FROM BOOKING b JOIN SEAT s ON s.seat_id = b.seat_id JOIN FLIGHT f ON f.flight_id = s.flight_id
WHERE b.status IN ('Confirmed','Cancelled') AND b.booking_id <> 4
ORDER BY b.booking_id;

-- One payment per booking. Amount = fare (business x2.5) + 12% taxes and fees.
INSERT INTO PAYMENT (amount, payment_date, payment_method, payment_status, booking_id)
SELECT ROUND(f.base_fare * CASE WHEN s.seat_class = 'Business' THEN 2.5 ELSE 1 END * 1.12, 2), b.booking_date,
       CASE WHEN b.status = 'Pending' THEN NULL WHEN b.booking_id % 4 = 0 THEN 'Card' WHEN b.booking_id % 4 = 1 THEN 'UPI' WHEN b.booking_id % 4 = 2 THEN 'NetBanking' ELSE 'Wallet' END,
       CASE b.status WHEN 'Confirmed' THEN 'Paid' WHEN 'Pending' THEN 'Pending' ELSE CASE WHEN b.booking_id = 4 THEN 'Failed' ELSE 'Refunded' END END,
       b.booking_id
FROM BOOKING b JOIN SEAT s ON s.seat_id = b.seat_id JOIN FLIGHT f ON f.flight_id = s.flight_id
ORDER BY b.booking_id;
